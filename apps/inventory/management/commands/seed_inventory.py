    def _seed_tracking(self, tenant, items):
        """5.6 Inventory Tracking & Control â€” status classifications + reservations.

        Classifications land only on spots the ledger shows holding stock (read live via
        ``_stocked_spots``), each for a SMALL slice of that spot so a visible remainder
        stays unclassified and availability never reads as fabricated. Reservations are
        walked through the REAL release/cancel actions like 5.5's cross-docks, so their
        statuses carry genuine audit rows, and the ACTIVE ones are capped at the anchor
        spot's ledger balance minus existing classifications (the page's own available
        figure) so a modest spot is never seeded into permanent negative availability;
        direct model creation deliberately bypasses the form's ATP check (that guard is
        for user input).
        """
        spots = self._stocked_spots(tenant)
        items_by_pk = {i.pk: i for i in items}
        locations_by_pk = {loc.pk: loc for loc in Location.objects.filter(tenant=tenant)}

        # --- stock status classifications ---------------------------------------------------
        if StockStatus.objects.filter(tenant=tenant).exists():
            self.stdout.write(f"  {tenant.name}: stock statuses already present, skipping.")
        elif not spots:
            self.stdout.write(
                f"  {tenant.name}: no stocked locations yet â€” run `seed_scm` first, "
                "skipping stock-status classifications.")
        else:
            created = 0
            for index, spot in enumerate(spots[:6]):
                status, reason = STATUS_SCRIPTS[index % len(STATUS_SCRIPTS)]
                item = items_by_pk.get(spot["item_id"])
                location = locations_by_pk.get(spot["location_id"])
                if item is None or location is None:
                    continue
                quantity = min(Decimal("3"), spot["qty"])
                if quantity <= Decimal("0"):
                    continue
                StockStatus.objects.create(
                    tenant=tenant, item=item, location=location, status=status,
                    quantity=quantity, reason=reason)
                created += 1
            self.stdout.write(self.style.SUCCESS(
                f"  {tenant.name}: {created} stock-status classifications."))

        # --- reservations, walked through the real actions -------------------------------------
        if InventoryReservation.objects.filter(tenant=tenant).exists():
            self.stdout.write(f"  {tenant.name}: reservations already present, skipping.")
            return
        User = get_user_model()
        user = User.objects.filter(tenant=tenant).order_by("pk").first()
        if user is None:
            self.stdout.write(self.style.WARNING(
                f"  {tenant.name}: no workspace user to attribute reservations to â€” "
                "skipping that seed."))
            return

        if spots:
            anchor = spots[0]
            demo_item = items_by_pk.get(anchor["item_id"]) or items[0]
            demo_location = (locations_by_pk.get(anchor["location_id"])
                             or Location.objects.filter(tenant=tenant).first())
        else:
            demo_item = items[0]
            demo_location = Location.objects.filter(tenant=tenant).first()
        if demo_location is None:
            self.stdout.write(
                f"  {tenant.name}: no locations â€” run `seed_scm` first, skipping reservations.")
            return

        # Demo claims are capped at the anchor spot's REAL headroom: ledger balance minus
        # what classifications already hold back â€” the same available figure the Real-Time
        # Stock Levels page derives. Direct model creation bypasses the form's ATP check
        # (that guard is for user input), so the cap here is what keeps a modest spot from
        # being seeded into permanently negative availability; a claim with no room left
        # is skipped rather than squeezed to an arbitrary fraction.
        on_hand = (StockMove.objects.filter(tenant=tenant, item=demo_item,
                                            location=demo_location)
                   .aggregate(q=Sum("quantity"))["q"] or Decimal("0"))
        classified = (StockStatus.objects.filter(tenant=tenant, item=demo_item,
                                                 location=demo_location)
                      .exclude(status="active")
                      .aggregate(s=Sum("quantity"))["s"] or Decimal("0"))
        room = max(on_hand - classified, Decimal("0"))

        summary = []
        reserved_qty = min(Decimal("4"), room)
        released_qty = min(Decimal("3"), room - reserved_qty)

        if reserved_qty > Decimal("0"):
            reserved = InventoryReservation.objects.create(
                tenant=tenant, item=demo_item, location=demo_location,
                purpose="sales_order", reference="SO-SEED-301", quantity=reserved_qty,
                reserved_by=user, notes="Seeded hold for an open customer order.")
            summary.append(f"{reserved.number} reserved")

        if released_qty > Decimal("0"):
            released = InventoryReservation(
                tenant=tenant, item=demo_item, location=demo_location,
                purpose="job", reference="JOB-0042", quantity=released_qty,
                reserved_by=user, notes="Seeded lock handed to the floor.")
            released.save()
            released.release(user)
            summary.append(f"{released.number} released")

        # Cancelled holds nothing back â€” it seeds unconditionally as the lifecycle demo.
        cancelled = InventoryReservation(
            tenant=tenant, item=demo_item, location=demo_location,
            purpose="project", reference="PRJ-2026-Q3", quantity=Decimal("2"),
            reserved_by=user, notes="Seeded claim dropped when the project paused.")
        cancelled.save()
        cancelled.cancel(user)
        summary.append(f"{cancelled.number} cancelled")

        self.stdout.write(self.style.SUCCESS(
            f"  {tenant.name}: {len(summary)} reservations ({' / '.join(summary)})."))

    def _seed_lot_tracking(self, tenant, items):
        """5.8 Lot & Serial Number Tracking â€” numbering rules, shelf-life policies,
        and expiry-dated demo lots minted through the REAL generation path.

        The tracked SKUs (WS-16 / MON-27, flipped to ``tracking='lot'`` by 4.9's
        seeder) get one tenant-default rule plus an item-specific override so the
        most-specific-wins resolution is demonstrable, a policy per item for the FEFO
        board, and three batches per anchor item carrying an expired / warning-window
        / healthy date â€” each minted via ``LotNumberRule.generate`` (the same code the
        Generate button runs) and given REAL ledger stock through the same posting
        shape ``seed_scm`` uses for its opening balances. Idempotent on the demo
        marker in the lot notes, so user-minted numbers are never touched on re-runs.
        """
