"""Sales 8.13 — The Marketing Alignment & Attribution console (derived, read-only).

This is the "Campaign Performance Integration" surface: marketing campaign ROI, cost per lead,
and the pipeline generated by each campaign, plus the MQL funnel, content engagement ranking and
event attendance rollups.

EVERY FIGURE HERE IS DERIVED. Nothing on this page is stored. Campaign ROI, cost per lead and
pipeline are computed on the fly from `CampaignAttribution` + `AttributionTouchpoint` +
`crm.Campaign`, so a rollup can never drift from the rows it summarises. The attribution model
is a page parameter (`?model=`), which is what lets a team run first-touch and last-touch side
by side over the same journey.

NO JournalEntry is posted by 8.13 (L29). The revenue shown is marketing-side attribution of
revenue recognised elsewhere -- it is not a financial posting.
"""
from decimal import Decimal

from django.contrib.auth.decorators import login_required
from django.db.models import Avg, Count, F, Q, Sum
from django.shortcuts import render
from django.utils import timezone

from apps.crm.models import Campaign
from apps.sales.models.MarketingAlignment.AttributionTouchpoints import (
    TOUCH_CHANNEL_CHOICES,
    AttributionTouchpoint,
)
from apps.sales.models.MarketingAlignment.CampaignAttributions import (
    ATTRIBUTION_MODEL_CHOICES,
    CampaignAttribution,
)
from apps.sales.models.MarketingAlignment.ContentEngagements import ContentEngagement
from apps.sales.models.MarketingAlignment.MarketingEvents import (
    EventRegistration,
    MarketingEvent,
)
from apps.sales.models.MarketingAlignment.MqlHandoffs import MqlHandoff
from apps.sales.models.SalesEnablement.EnablementContents import EnablementContent

ZERO = Decimal("0.00")


def _roi_pct(revenue, cost):
    """Return on investment %, or None when there is no cost to divide by."""
    cost = Decimal(cost or 0)
    if not cost:
        return None
    return (Decimal(revenue or 0) - cost) / cost * 100


@login_required
def marketing_attribution_console(request):
    tenant = request.tenant

    # The attribution model is a page parameter. An unknown value falls back to first-touch
    # rather than silently showing an empty rollup.
    requested_model = request.GET.get("model", "").strip()
    valid_models = {code for code, _label in ATTRIBUTION_MODEL_CHOICES}
    active_model = requested_model if requested_model in valid_models else "first_touch"

    touchpoints = AttributionTouchpoint.objects.filter(tenant=tenant)
    attributions = CampaignAttribution.objects.filter(
        tenant=tenant, attribution_model=active_model
    )

    # ---- Campaign rollup -------------------------------------------------------------------
    tp_by_campaign = {
        row["campaign_id"]: row
        for row in touchpoints.values("campaign_id").annotate(
            touchpoint_count=Count("id"),
            lead_count=Count("lead_id", distinct=True),
            pipeline_value=Sum("engagement_value"),
        )
    }
    attr_by_campaign = {
        row["touchpoint__campaign_id"]: row
        for row in attributions.values("touchpoint__campaign_id").annotate(
            attributed_revenue=Sum("attributed_revenue"),
            attributed_cost=Sum("attributed_cost"),
        )
    }

    campaign_ids = set(tp_by_campaign) | set(attr_by_campaign)
    campaign_ids.discard(None)
    campaigns = {
        c.pk: c
        for c in Campaign.objects.filter(tenant=tenant, pk__in=campaign_ids)
    }

    campaign_rows = []
    total_spend = ZERO
    total_attributed_revenue = ZERO
    total_leads = 0
    for campaign_pk, campaign in campaigns.items():
        tp = tp_by_campaign.get(campaign_pk, {})
        attr = attr_by_campaign.get(campaign_pk, {})
        spend = Decimal(campaign.budget_actual or 0)
        revenue = Decimal(attr.get("attributed_revenue") or 0)
        lead_count = tp.get("lead_count") or 0
        cost_per_lead = (spend / lead_count) if (lead_count and spend) else None
        campaign_rows.append(
            {
                "campaign": campaign,
                "spend": spend,
                "attributed_revenue": revenue,
                "roi_pct": _roi_pct(revenue, spend),
                "cost_per_lead": cost_per_lead,
                "pipeline_value": Decimal(tp.get("pipeline_value") or 0),
                "lead_count": lead_count,
                "touchpoint_count": tp.get("touchpoint_count") or 0,
            }
        )
        total_spend += spend
        total_attributed_revenue += revenue
        total_leads += lead_count

    campaign_rows.sort(key=lambda row: (row["attributed_revenue"], row["spend"]), reverse=True)

    # ---- Channel rollup -------------------------------------------------------------------
    tp_by_channel = {
        row["channel"]: row
        for row in touchpoints.values("channel").annotate(
            touchpoints=Count("id"),
            cost=Sum("cost"),
        )
    }
    attr_by_channel = {
        row["touchpoint__channel"]: row
        for row in attributions.values("touchpoint__channel").annotate(
            attributed_revenue=Sum("attributed_revenue"),
        )
    }
    channel_labels = dict(TOUCH_CHANNEL_CHOICES)
    channel_rows = []
    for channel, label in TOUCH_CHANNEL_CHOICES:
        tp = tp_by_channel.get(channel)
        if not tp:
            continue
        attr = attr_by_channel.get(channel, {})
        revenue = Decimal(attr.get("attributed_revenue") or 0)
        cost = Decimal(tp.get("cost") or 0)
        channel_rows.append(
            {
                "channel": channel,
                "label": label,
                "touchpoints": tp.get("touchpoints") or 0,
                "cost": cost,
                "attributed_revenue": revenue,
                "roi_pct": _roi_pct(revenue, cost),
            }
        )
    channel_rows.sort(key=lambda row: row["attributed_revenue"], reverse=True)

    # ---- MQL funnel -----------------------------------------------------------------------
    handoffs = MqlHandoff.objects.filter(tenant=tenant)
    now = timezone.now()
    funnel = handoffs.aggregate(
        pending=Count("id", filter=Q(status="pending")),
        accepted=Count("id", filter=Q(status="accepted")),
        rejected=Count("id", filter=Q(status="rejected")),
        expired=Count("id", filter=Q(status="expired")),
        converted=Count("id", filter=Q(status="converted")),
        total=Count("id"),
        breaches=Count(
            "id",
            filter=Q(responded_at__isnull=False, responded_at__gt=F("sla_due_at"))
            | Q(status="pending", sla_due_at__lt=now),
        ),
    )
    decided = funnel["accepted"] + funnel["rejected"]
    mql_funnel = {
        "pending": funnel["pending"],
        "accepted": funnel["accepted"],
        "rejected": funnel["rejected"],
        "expired": funnel["expired"],
        "converted": funnel["converted"],
        "total": funnel["total"],
        "acceptance_rate_pct": (
            round(funnel["accepted"] / decided * 100, 1) if decided else None
        ),
        "sla_compliance_pct": (
            round(100 - (funnel["breaches"] / funnel["total"] * 100), 1)
            if funnel["total"]
            else None
        ),
    }
    response_pairs = list(
        handoffs.filter(responded_at__isnull=False).values_list(
            "responded_at", "handoff_at"
        )
    )
    response_hours = [
        (responded - handed).total_seconds() / 3600
        for responded, handed in response_pairs
        if responded is not None and handed is not None
    ]
    mql_funnel["avg_response_hours"] = (
        round(sum(response_hours) / len(response_hours), 2) if response_hours else None
    )

    # ---- Content engagement ranking -------------------------------------------------------
    content_agg = (
        ContentEngagement.objects.filter(tenant=tenant)
        .values("content_id")
        .annotate(
            engagements=Count("id"),
            avg_score=Avg("engagement_score"),
            revenue_attributed=Sum("revenue_attributed"),
        )
        .order_by("-revenue_attributed")[:8]
    )
    content_ids = [row["content_id"] for row in content_agg if row["content_id"]]
    # Resolve the content titles in one extra query rather than one per row.
    titles = dict(
        EnablementContent.objects.filter(pk__in=content_ids).values_list("pk", "title")
    )
    content_rows = [
        {
            "content": titles.get(row["content_id"], "—"),
            "engagements": row["engagements"],
            "avg_score": round(row["avg_score"] or 0, 1),
            "revenue_attributed": Decimal(row["revenue_attributed"] or 0),
        }
        for row in content_agg
    ]

    # ---- Event attendance rollup ----------------------------------------------------------
    event_agg = (
        EventRegistration.objects.filter(tenant=tenant)
        .values("event_id")
        .annotate(
            registrations=Count("id"),
            attended=Count("id", filter=Q(registration_status="attended")),
            revenue=Sum("revenue_attributed"),
        )
        .order_by("-registrations")[:8]
    )
    event_ids = [row["event_id"] for row in event_agg if row["event_id"]]
    event_names = dict(
        MarketingEvent.objects.filter(pk__in=event_ids).values_list("pk", "name")
    )
    event_rows = []
    for row in event_agg:
        registrations = row["registrations"]
        event_rows.append(
            {
                "event": event_names.get(row["event_id"], "—"),
                "registrations": registrations,
                "attended": row["attended"],
                "show_up_pct": (
                    round(row["attended"] / registrations * 100, 1)
                    if registrations
                    else None
                ),
                "revenue_per_registrant": (
                    Decimal(row["revenue"] or 0) / registrations
                    if registrations
                    else None
                ),
            }
        )

    # ---- Headline stats -------------------------------------------------------------------
    avg_cost_per_lead = (total_spend / total_leads) if (total_leads and total_spend) else None
    stats = {
        "total_touchpoints": touchpoints.count(),
        "total_spend": total_spend,
        "total_attributed_revenue": total_attributed_revenue,
        "blended_roi_pct": _roi_pct(total_attributed_revenue, total_spend),
        "avg_cost_per_lead": avg_cost_per_lead,
        "mql_total": mql_funnel["total"],
        "mql_accepted": mql_funnel["accepted"],
        "mql_acceptance_rate_pct": mql_funnel["acceptance_rate_pct"],
        "sla_compliance_pct": mql_funnel["sla_compliance_pct"],
        "content_engagements": ContentEngagement.objects.filter(tenant=tenant).count(),
        "events": MarketingEvent.objects.filter(tenant=tenant).count(),
    }

    context = {
        "stats": stats,
        "campaign_rows": campaign_rows,
        "channel_rows": channel_rows,
        "mql_funnel": mql_funnel,
        "content_rows": content_rows,
        "event_rows": event_rows,
        "model_choices": ATTRIBUTION_MODEL_CHOICES,
        "active_model": active_model,
        "active_model_label": dict(ATTRIBUTION_MODEL_CHOICES).get(active_model, active_model),
    }
    return render(
        request,
        "sales/marketingalignment/attribution_console.html",
        context,
    )
