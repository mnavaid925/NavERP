"""Sales 8.8 — the playbook register, its CRUD, and the generation verb.

**`task_template_generate` IS THE SUB-MODULE'S ONLY WRITER OF REAL CRM DATA.** It creates
``crm.CrmTask`` rows — CRM 1.5's table, not a parallel one — and it is the whole reason this
sub-module exists without owning a task master. It writes those rows **and** the template's frozen
receipt (``last_generated_on`` / ``generated_count``) inside ONE ``transaction.atomic()`` block, so a
template can never claim a run whose tasks were rolled back, and a run can never lose its receipt.

**IDEMPOTENT BY CONSTRUCTION (research §8, G16).** Two guards, not one:

1. A per-(step, target) "already generated at this due date" check, so a second run on the same
   anchor date creates **zero** tasks rather than a duplicate set.
2. ``last_generated_on`` is compared against the anchor date, so an unchanged re-run short-circuits
   before the walk even starts.

The walk is bounded by ``MAX_TEMPLATE_TARGETS``. It is a cap on how many targets one run fans out
over, and the page SAYS when it was hit — a silently-truncated fan-out would read as a complete one,
which is L40's exact failure.

**Every scan is ORDERED.** The "most recent task per target" lookups and the target ordering both
carry an explicit tie-break, because anything feeding a key comparison must be deterministic (L61).
"""
