@require_POST
@login_required
@tenant_admin_required
def task_template_delete(request, pk):
    obj = get_object_or_404(_template_queryset(request), pk=pk)
    step_count = obj.steps.count()
    with transaction.atomic():
        locked = TaskTemplate.objects.select_for_update().get(pk=obj.pk, tenant=request.tenant)
        write_audit_log(
            request.user,
            locked,
            "delete",
            {
                "action": "task_template",
                "name": locked.name,
                "cadence": locked.cadence,
                "target_type": locked.target_type,
                "steps": step_count,
                "generated_count": locked.generated_count,
            },
            tenant=request.tenant,
        )
        # Steps cascade (they have no history of their own). Generated crm.CrmTask rows DO NOT — they
        # are ordinary tasks in CRM 1.5's table and must survive the playbook being retired.
        locked.delete()
    messages.success(
        request,
        f"Template {obj.number} deleted. Any tasks it generated stay in the task list.",
    )
    return redirect("sales:task_template_list")


@require_POST
@login_required
@tenant_admin_required
def task_template_generate(request, pk):
    """COMMIT. Materialise ``crm.CrmTask`` rows and stamp the receipt — in ONE transaction."""
    obj = get_object_or_404(_template_queryset(request), pk=pk)
    today = timezone.localdate()
    generatable, why_not = obj.is_generatable
    if not generatable:
        messages.error(request, why_not or "This template cannot generate tasks.")
        return redirect("sales:task_template_detail", pk=obj.pk)

    anchor = _next_anchor(today, obj.cadence)
    # G16, guard 2 — short-circuit before the walk. An unchanged re-run creates nothing.
    if obj.last_generated_on == anchor:
        messages.info(
            request,
            f"Already generated on {anchor:%d %b %Y}. A run does nothing twice on the same anchor.",
        )
        return redirect("sales:task_template_detail", pk=obj.pk)

    steps = list(obj.steps.all())
    targets, truncated = _template_targets(obj, today)
    owner = obj.owner
    created = 0
    skipped = 0
    with transaction.atomic():
        locked = TaskTemplate.objects.select_for_update().get(pk=obj.pk, tenant=request.tenant)
        # G16, guard 1 — re-check the anchor INSIDE the transaction, so two concurrent runs cannot
        # both pass the check above and each fan out.
        if locked.last_generated_on != anchor:
            # Idempotency is per (step, target, due_date): a step whose due date is already taken by
            # a task for that target is skipped, never duplicated. The scan is bounded to the window
            # the steps can actually land in (MAX_STEP_OFFSET_DAYS either side of the anchor), so the
            # existence check is a bounded index lookup rather than a whole-history load.
            window_lo = anchor - timedelta(days=MAX_STEP_OFFSET_DAYS)
            window_hi = anchor + timedelta(days=MAX_STEP_OFFSET_DAYS)
            existing = set(
                CrmTask.objects.filter(
                    tenant=locked.tenant,
                    due_date__gte=window_lo,
                    due_date__lte=window_hi,
                ).values_list("due_date", "party_id", "related_opportunity_id")
            )
            for target in targets:
                for step in steps:
                    due = anchor + timedelta(days=step.offset_days + locked.default_offset_days)
                    key = (due, target["party"].pk if target["party"] else None,
                           target["opportunity"].pk if target["opportunity"] else None)
                    if key in existing:
                        skipped += 1
                        continue
                    CrmTask.objects.create(
                        tenant=locked.tenant,
                        subject=f"{step.title} — {target['label']}",
                        type=step.task_type,
                        priority=step.priority,
                        status="open",
                        due_date=due,
                        owner=owner,
                        party=target["party"],
                        related_opportunity=target["opportunity"],
                        description=step.instructions,
                    )
                    existing.add(key)
                    created += 1
            # Frozen receipt, written INSIDE the same block as the rows it describes (L22).
            locked.last_generated_on = anchor
            locked.generated_count = (locked.generated_count or 0) + created
            locked.save(update_fields=["last_generated_on", "generated_count", "updated_at"])
            write_audit_log(
                request.user,
                locked,
                "update",
                {
                    "action": "task_template_generate",
                    "name": locked.name,
                    "anchor": anchor.isoformat(),
                    "cadence": locked.cadence,
                    "target_type": locked.target_type,
                    "targets": len(targets),
                    "truncated": truncated,
                    "created": created,
                    "skipped_existing": skipped,
                },
                tenant=locked.tenant,
            )
    messages.success(
        request,
        f"Generated {created} task(s) for {anchor:%d %b %Y}.",
    )
    if skipped:
        messages.info(request, f"{skipped} task(s) already existed for that date and were left alone.")
    if truncated:
        messages.warning(
            request,
            f"Only the first {MAX_TEMPLATE_TARGETS} targets were used — the run is capped. "
            "Narrow the target type or split the playbook.",
        )
    return redirect("sales:task_template_detail", pk=obj.pk)