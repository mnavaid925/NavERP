PAGE_SIZE = 15

#: How many targets ONE run fans out over. Surfaced on the page when it binds (L40: a cap that
#: silently truncates reads as completeness).
MAX_TEMPLATE_TARGETS = 100

#: Most recent OPEN tasks for the template's owner shown on its detail page. Deliberately NOT
#: labelled "generated by this template": a generated row is an ordinary ``crm.CrmTask`` with no
#: back-reference (a back-reference would be a schema change to CRM 1.5's table, which is exactly
#: what the L36 ruling forbids). The receipt below — `last_generated_on` / `generated_count` — is the
#: honest record of what a run produced.
MAX_OWNER_OPEN_TASKS = 25


def _template_queryset(request):
    return TaskTemplate.objects.filter(tenant=request.tenant).select_related(
        "activity_type", "territory", "owner",
    )


def _choice_context(request):
    tenant = request.tenant
    return {
        "cadence_choices": TaskTemplate.CADENCE_CHOICES,
        "target_type_choices": TaskTemplate.TARGET_TYPE_CHOICES,
        "task_type_choices": TaskTemplate.TASK_TYPE_CHOICES,
        "priority_choices": TaskTemplate.PRIORITY_CHOICES,
        "active_choices": [("active", "Active"), ("inactive", "Inactive")],
        "owners": tenant_users(tenant).order_by("username"),
        "territories": (
            Territory.objects.filter(tenant=tenant, is_active=True).order_by("name")
            if tenant is not None
            else Territory.objects.none()
        ),
        "activity_types": ActivityType.objects.filter(tenant=tenant, is_active=True).order_by("display_order", "name"),
    }


def _next_anchor(today, cadence):
    """The next anchor date on or after ``today`` for a cadence. Uses the stdlib only —
    ``python-dateutil`` is not installed in this project, and ``calendar.monthrange`` is the same
    month-end clamp ``crm.CrmTask._next_due`` uses."""
    if cadence == "daily":
        return today
    if cadence == "weekly":
        return today + timedelta(days=7 - today.weekday())
    if cadence == "biweekly":
        return today + timedelta(days=14 - today.weekday())
    if cadence == "monthly":
        year, month = today.year, today.month
        if today.day >= 28:
            year, month = (year + 1, 1) if month == 12 else (year, month + 1)
        return timezone.datetime(year, month, 1).date()
    if cadence == "quarterly":
        quarter_start_month = ((today.month - 1) // 3) * 3 + 1
        year, month = today.year, quarter_start_month
        if today.month >= quarter_start_month + 3:
            year, month = (year + 1, 1) if month == 10 else (year, month + 3)
        return timezone.datetime(year, month, 1).date()
    return today


def _template_targets(template, today):
    """The bounded list of things this template fans out over.

    Returns ``(targets, truncated)``. Each target is a dict so the four target kinds stay one shape
    downstream: an opportunity, an account, or a territory expanded to its accounts.
    """
    if template.target_type == "territory":
        accounts = list(
            Party.objects.filter(tenant=template.tenant, kind="organization")
            .order_by("name")[:MAX_TEMPLATE_TARGETS + 1]
        )
        truncated = len(accounts) > MAX_TEMPLATE_TARGETS
        return [
            {"label": a.name, "party": a, "opportunity": None, "account": a}
            for a in accounts[:MAX_TEMPLATE_TARGETS]
        ], truncated
    if template.target_type == "account":
        accounts = list(
            Party.objects.filter(tenant=template.tenant, kind="organization")
            .order_by("name")[:MAX_TEMPLATE_TARGETS + 1]
        )
        truncated = len(accounts) > MAX_TEMPLATE_TARGETS
        return [
            {"label": a.name, "party": a, "opportunity": None, "account": a}
            for a in accounts[:MAX_TEMPLATE_TARGETS]
        ], truncated
    opportunities = list(
        Opportunity.objects.filter(tenant=template.tenant)
        .exclude(stage__in=["closed_won", "closed_lost"])
        .select_related("account")
        .order_by("-close_date", "name")[:MAX_TEMPLATE_TARGETS + 1]
    )
    truncated = len(opportunities) > MAX_TEMPLATE_TARGETS
    return [
        {
            "label": o.name,
            "party": o.account,
            "opportunity": o,
            "account": o.account,
        }
        for o in opportunities[:MAX_TEMPLATE_TARGETS]
    ], truncated


@login_required
def task_template_list(request):
    stats = _template_queryset(request).aggregate(
        total=Count("id"),
        active=Count("id", filter=Q(is_active=True)),
        never_generated=Count("id", filter=Q(last_generated_on__isnull=True)),
        with_steps=Count("id", filter=Q(steps__isnull=False)),
    )
    return crud_list(
        request,
        _template_queryset(request).annotate(_step_count=Count("steps", distinct=True)),
        LIST_TEMPLATE,
        search_fields=["number", "name", "description"],
        filters=[
            ("cadence", "cadence", False),
            ("target_type", "target_type", False),
            ("task_type", "task_type", False),
            ("priority", "priority", False),
            ("active", "is_active", True),
        ],
        extra_context={
            "page_size": PAGE_SIZE,
            **_choice_context(request),
            "stats": stats,
        },
        per_page=PAGE_SIZE,
    )


