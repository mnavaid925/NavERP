@login_required
def task_template_detail(request, pk):
    obj = get_object_or_404(_template_queryset(request), pk=pk)
    steps = obj.steps.all()
    today = timezone.localdate()
    generatable, why_not = obj.is_generatable
    caveats = []
    if why_not:
        caveats.append(why_not)
    if obj.target_type == "territory" and not obj.territory_id:
        caveats.append("This template targets a territory but names none, so a run would refuse it.")
    elif obj.target_type != "territory" and obj.territory_id:
        caveats.append(
            "This template names a territory but targets "
            f"{obj.get_target_type_display().lower()}s, which the model refuses."
        )
    # A dry-run preview of what ONE run would create, bounded exactly as the run is. The detail page
    # therefore cannot disagree with the run's own scope — the same evaluator feeds both.
    preview_targets, truncated = ([], False)
    if generatable:
        preview_targets, truncated = _template_targets(obj, today)
    anchor = _next_anchor(today, obj.cadence)
    owner_open_tasks = (
        CrmTask.objects.filter(tenant=obj.tenant, owner=obj.owner, status__in=CrmTask.OPEN_STATUSES)
        .select_related("party", "related_opportunity")
        .order_by("due_date", "-pk")[:MAX_OWNER_OPEN_TASKS]
        if obj.owner_id
        else CrmTask.objects.none()
    )
    return render(request, DETAIL_TEMPLATE, {
        "obj": obj,
        "steps": steps,
        "step_count": steps.count(),
        "generatable": generatable,
        "caveats": caveats,
        "preview_targets": preview_targets[:25],
        "preview_total": len(preview_targets),
        "preview_truncated": truncated,
        "preview_cap": MAX_TEMPLATE_TARGETS,
        "next_anchor": anchor,
        "owner_open_tasks": owner_open_tasks,
        "owner_open_task_cap": MAX_OWNER_OPEN_TASKS,
        **_choice_context(request),
    })


