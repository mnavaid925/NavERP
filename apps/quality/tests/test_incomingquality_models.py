def _incomingquality_models_sample_date(days_offset=0):
    """Return date relative to today."""
    return timezone.now().date() + timedelta(days=days_offset)


def _incomingquality_models_make_measurements(values, characteristic="Diameter"):
    """Build measurements_data list from raw numeric or special values."""
    return [
        {
            "sample_no": idx + 1,
            "characteristic": characteristic,
            "value": val,
            "is_pass": True,
        }
        for idx, val in enumerate(values)
    ]


