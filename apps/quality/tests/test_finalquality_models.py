def test_finalquality_coc_foreign_keys_and_cascade(
    tenant_a, customer_party_a, admin_user, final_lot_a
):
    """Verify foreign keys and cascade behavior upon customer deletion."""
    temp_customer = Party.objects.create(
        tenant=tenant_a,
        name="Temporary CoC Customer",
    )
    coc = CertificateOfConformance.objects.create(
        tenant=tenant_a,
        customer=temp_customer,
        title="Ephemeral CoC",
        inspection_lot=final_lot_a,
        authorized_signatory=admin_user,
    )

    assert coc.customer == temp_customer
    assert coc.inspection_lot == final_lot_a
    assert coc.authorized_signatory == admin_user
    assert final_lot_a.certificates_of_conformance.filter(pk=coc.pk).exists()
    assert admin_user.cocs_authorized.filter(pk=coc.pk).exists()

    # Deleting customer should cascade delete the CoC
    coc_pk = coc.pk
    temp_customer.delete()
    assert not CertificateOfConformance.objects.filter(pk=coc_pk).exists()


