    """Verify all 7 conditions required for is_cleared_to_ship property."""
    # 1. Fully compliant standard release
    rel = QualityReleaseAuthorization.objects.create(
        tenant=tenant_a,
        customer=customer_party_a,
        title="Full Release Clearance Check",
        status="authorized",
        release_disposition="released_full",
        is_on_hold=False,
        final_inspection_passed=True,
        no_open_ncrs_or_capas=True,
        packaging_label_approved=True,
        coc_issued_and_signed=True,
    )
    assert rel.is_cleared_to_ship is True

    # 2. Conditional release with concession is also cleared to ship
    rel.release_disposition = "conditional_release"
    assert rel.is_cleared_to_ship is True

    # 3. Status not authorized fails clearance
    rel.status = "draft"
    assert rel.is_cleared_to_ship is False

    rel.status = "active_hold"
    assert rel.is_cleared_to_ship is False

    rel.status = "cancelled"
    assert rel.is_cleared_to_ship is False

    # Reset status
    rel.status = "authorized"

    # 4. Blocked / quarantined disposition fails clearance
    rel.release_disposition = "quarantined_hold"
    assert rel.is_cleared_to_ship is False

    rel.release_disposition = "pending_review"
    assert rel.is_cleared_to_ship is False

    rel.release_disposition = "rejected_shipping_blocked"
    assert rel.is_cleared_to_ship is False

    # Reset disposition
    rel.release_disposition = "released_full"

    # 5. Quality hold flag fails clearance
    rel.is_on_hold = True
    assert rel.is_cleared_to_ship is False
    rel.is_on_hold = False

    # 6. Final inspection failure fails clearance
    rel.final_inspection_passed = False
    assert rel.is_cleared_to_ship is False
    rel.final_inspection_passed = True

    # 7. Open NCRs or CAPAs fails clearance
    rel.no_open_ncrs_or_capas = False
    assert rel.is_cleared_to_ship is False
    rel.no_open_ncrs_or_capas = True

    # 8. Packaging label unapproved fails clearance
    rel.packaging_label_approved = False
    assert rel.is_cleared_to_ship is False
    rel.packaging_label_approved = True

    # 9. CoC unsigned fails clearance
    rel.coc_issued_and_signed = False
    assert rel.is_cleared_to_ship is False
    rel.coc_issued_and_signed = True

    # All restored -> True
    assert rel.is_cleared_to_ship is True


