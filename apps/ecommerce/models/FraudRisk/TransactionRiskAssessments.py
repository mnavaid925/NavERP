from decimal import Decimal
from django.conf import settings
from django.db import models
from apps.ecommerce.models._base import TenantNumbered


class TransactionRiskAssessment(TenantNumbered):
    NUMBER_PREFIX = "ETRA"

    RISK_TIER_CHOICES = [
        ("low", "Low Risk (0-25)"),
        ("medium", "Medium Risk (26-60)"),
        ("high", "High Risk (61-85)"),
        ("critical", "Critical Risk (86-100)"),
    ]

    RECOMMENDED_ACTION_CHOICES = [
        ("approve", "Approve"),
        ("review", "Manual Review"),
        ("challenge", "Challenge (3DS)"),
        ("reject", "Reject / Decline"),
    ]

    ACTUAL_DECISION_CHOICES = [
        ("pending", "Pending Assessment"),
        ("approved_auto", "Auto-Approved"),
        ("approved_manual", "Approved by Analyst"),
        ("declined_auto", "Auto-Declined"),
        ("declined_manual", "Declined by Analyst"),
        ("challenged", "Challenged / 3DS Required"),
    ]

    AVS_RESULT_CHOICES = [
        ("match", "Full Address & Zip Match"),
        ("partial", "Partial Match (Zip or Street only)"),
        ("no_match", "No Match"),
        ("not_checked", "Not Checked / Unsupported"),
    ]

    CVV_RESULT_CHOICES = [
        ("match", "CVV Match"),
        ("no_match", "CVV No Match"),
        ("not_provided", "Not Provided"),
        ("not_checked", "Not Checked"),
    ]

    order = models.ForeignKey(
        "ecommerce.EcommerceOrder",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="risk_assessments",
        help_text="Evaluated e-commerce order (if already placed)",
    )
    customer_party = models.ForeignKey(
        "core.Party",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="fraud_assessments",
        help_text="Customer party entity from core spine",
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="ecommerce_risk_assessments",
        help_text="Authenticated user account initiating checkout",
    )
    transaction_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        help_text="Gross financial sum evaluated for fraud risk",
    )
    currency = models.ForeignKey(
        "accounting.Currency",
        on_delete=models.PROTECT,
        related_name="fraud_assessments",
        help_text="Transaction billing currency",
    )
    risk_score = models.IntegerField(
        default=0,
        help_text="Composite risk score from 0 (very low risk) to 100 (critical fraud risk)",
    )
    risk_tier = models.CharField(
        max_length=20,
        choices=RISK_TIER_CHOICES,
        default="low",
        help_text="Categorical risk rating based on score",
    )
    recommended_action = models.CharField(
        max_length=25,
        choices=RECOMMENDED_ACTION_CHOICES,
        default="approve",
        help_text="Algorithmic verdict generated by scoring engine",
    )
    actual_decision = models.CharField(
        max_length=25,
        choices=ACTUAL_DECISION_CHOICES,
        default="pending",
        help_text="Final operational action taken on transaction",
    )
    avs_result_code = models.CharField(
        max_length=20,
        choices=AVS_RESULT_CHOICES,
        default="not_checked",
        help_text="Card network Address Verification Service result code",
    )
    cvv_result_code = models.CharField(
        max_length=20,
        choices=CVV_RESULT_CHOICES,
        default="not_checked",
        help_text="Card Verification Value check result",
    )
    ip_address = models.GenericIPAddressField(
        null=True,
        blank=True,
        help_text="Originating client IP address",
    )
    billing_country = models.CharField(
        max_length=2,
        blank=True,
        default="",
        help_text="ISO 2-letter country code from billing address",
    )
    ip_country = models.CharField(
        max_length=2,
        blank=True,
        default="",
        help_text="ISO 2-letter country code resolved from IP geolocation",
    )
    is_geo_mismatch = models.BooleanField(
        default=False,
        help_text="Whether billing country and IP country diverge",
    )
    is_proxy_or_vpn = models.BooleanField(
        default=False,
        help_text="Whether connection originated from known proxy, VPN, or TOR node",
    )
    device_fingerprint = models.CharField(
        max_length=128,
        blank=True,
        default="",
        help_text="Hash identifier representing client browser/device hardware profile",
    )
    velocity_count_24h = models.IntegerField(
        default=1,
        help_text="Number of attempted checkout transactions in prior 24 hours",
    )
    risk_factors_summary = models.TextField(
        blank=True,
        default="",
        help_text="Structured summary of triggered risk rules and signal penalties",
    )
    analyst_user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="reviewed_risk_assessments",
        help_text="Fraud analyst who reviewed and approved/declined transaction",
    )
    analyst_notes = models.TextField(
        blank=True,
        default="",
        help_text="Investigation commentary and decision notes from fraud analyst",
    )
    reviewed_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp when manual analyst review was completed",
    )

    class Meta:
        db_table = "ecommerce_transaction_risk_assessment"
        ordering = ["-created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["tenant", "number"],
                name="ecommerce_etra_tenant_num_uniq",
            ),
        ]
        indexes = [
            models.Index(fields=["tenant", "risk_tier"], name="idx_etra_ten_tier"),
            models.Index(fields=["tenant", "actual_decision"], name="idx_etra_ten_dec"),
            models.Index(fields=["tenant", "order"], name="idx_etra_ten_order"),
            models.Index(fields=["tenant", "customer_party"], name="idx_etra_ten_party"),
        ]

    def __str__(self):
        return f"{self.number} - Score: {self.risk_score} ({self.get_risk_tier_display()})"
